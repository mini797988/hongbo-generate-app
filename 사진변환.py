"""매장 사진을 인스타그램용 1080x1080 정사각형으로 바꿔 주는 프로그램.

- '자료' 폴더의 jpg, png 사진을 읽기만 한다 (원본은 건드리지 않는다)
- 가운데를 기준으로 정사각형으로 자른 뒤 1080x1080으로 맞춘다
- 로고 파일이 있으면 오른쪽 아래에 작게 넣는다 (없으면 건너뛴다)
- '완성' 폴더에 '오늘날짜_01.jpg' 형식으로 저장한다
"""
import json
import os
import re
from datetime import date
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageOps

기준폴더 = Path(__file__).resolve().parent
자료폴더 = 기준폴더 / "자료"
완성폴더 = 기준폴더 / "완성"

크기 = 1080
로고_비율 = 0.15      # 사진 가로 폭의 15%
바깥_여백 = 40        # 사진 가장자리에서 안쪽으로 40픽셀
흰판_여백 = 16        # 로고 둘레의 흰 바탕 두께
흰판_모서리 = 18      # 흰 바탕 모서리 둥글기
흰판_진하기 = 120     # 흰 바탕 진하기 (0 = 완전 투명, 255 = 불투명)
로고_이름들 = ["로고.jpg", "로고.jpeg", "로고.png"]


def 로고_찾기():
    """로고 파일을 찾는다. 없으면 None."""
    for 폴더 in (기준폴더, 자료폴더):
        for 이름 in 로고_이름들:
            경로 = 폴더 / 이름
            if 경로.is_file():
                return 경로
    return None


def 정사각형으로_자르기(그림):
    """가운데 기준으로 정사각형 자르기 후 1080x1080으로 맞춘다 (비율 유지)."""
    그림 = ImageOps.exif_transpose(그림).convert("RGB")
    return ImageOps.fit(그림, (크기, 크기), Image.LANCZOS, centering=(0.5, 0.5))


def 로고_준비(로고경로):
    로고 = Image.open(로고경로)
    로고 = ImageOps.exif_transpose(로고).convert("RGBA")
    너비 = round(크기 * 로고_비율)
    높이 = max(1, round(로고.height * 너비 / 로고.width))
    return 로고.resize((너비, 높이), Image.LANCZOS)


def 로고_넣기(사진, 로고):
    """오른쪽 아래에 부드러운 그림자가 있는 흰 둥근 사각 바탕 + 로고를 얹는다."""
    판너비 = 로고.width + 흰판_여백 * 2
    판높이 = 로고.height + 흰판_여백 * 2
    왼쪽 = 크기 - 바깥_여백 - 판너비
    위쪽 = 크기 - 바깥_여백 - 판높이

    # 그림자 (살짝 흐리게)
    그림자층 = Image.new("RGBA", 사진.size, (0, 0, 0, 0))
    ImageDraw.Draw(그림자층).rounded_rectangle(
        (왼쪽, 위쪽 + 4, 왼쪽 + 판너비, 위쪽 + 판높이 + 4),
        radius=흰판_모서리, fill=(0, 0, 0, 35),
    )
    그림자층 = 그림자층.filter(ImageFilter.GaussianBlur(8))

    # 반투명 흰 바탕 (뒤 사진이 은은하게 비치게)
    판층 = Image.new("RGBA", 사진.size, (0, 0, 0, 0))
    ImageDraw.Draw(판층).rounded_rectangle(
        (왼쪽, 위쪽, 왼쪽 + 판너비, 위쪽 + 판높이),
        radius=흰판_모서리, fill=(255, 255, 255, 흰판_진하기),
    )

    결과 = 사진.convert("RGBA")
    결과 = Image.alpha_composite(결과, 그림자층)
    결과 = Image.alpha_composite(결과, 판층)
    결과.alpha_composite(로고, (왼쪽 + 흰판_여백, 위쪽 + 흰판_여백))
    return 결과.convert("RGB")


def 다음_번호(접두사):
    """오늘 이미 저장한 파일이 있으면 그 다음 번호부터 시작한다."""
    번호들 = []
    for 파일 in 완성폴더.glob(f"{접두사}_*.jpg"):
        뒷부분 = 파일.stem.split("_")[-1]
        if 뒷부분.isdigit():
            번호들.append(int(뒷부분))
    return max(번호들, default=0) + 1


def 파일_찾기(이름들):
    """기준 폴더와 '자료' 폴더에서 이름이 맞는 파일을 찾는다. 없으면 None."""
    for 폴더 in (기준폴더, 자료폴더):
        for 이름 in 이름들:
            경로 = 폴더 / 이름
            if 경로.is_file():
                return 경로
    return None


def 키_읽기():
    """API 키를 환경 변수 또는 'api키.txt'에서 읽는다. 없으면 None."""
    키 = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if 키:
        return 키
    키파일 = 기준폴더 / "api키.txt"
    if 키파일.is_file():
        키 = 키파일.read_text(encoding="utf-8-sig").strip()
        if 키 and "여기에" not in 키:
            return 키
    return None


def 문구_만들기_AI():
    """(API 키가 있을 때) 가게 정보를 읽어 Claude에게 인스타그램 문구 3가지를 받아 '완성/홍보문구.txt'로 저장한다."""
    정보파일 = 파일_찾기(["가게정보.txt", "가게 정보.txt"])
    키 = 키_읽기()
    if not 정보파일 or not 키:
        return False

    가게정보 = 정보파일.read_text(encoding="utf-8")
    말투파일 = 파일_찾기(["내 말투.txt", "내말투.txt"])
    말투예시 = 말투파일.read_text(encoding="utf-8") if 말투파일 else ""

    요청 = f"""너는 동네 가게 사장님의 인스타그램 글을 대신 써 주는 도우미야.
아래 [가게 정보]를 보고 같은 내용을 세 채널(인스타그램, 네이버 블로그, 카카오톡 단골 공지)에 맞게 써 줘.

[가게 정보]
{가게정보}

[사장님이 직접 쓴 글 (이런 글이 정답이야. 말투 본보기로만 쓰고, 소재와 내용은 가져오지 마)]
{말투예시}

[사장님 말투 규칙 - 세 채널 모두 반드시 지켜]
- 끝맺음은 "~습니다 / ~합니다" 체. "~요", "~해요"로 끝내지 마. 구어체("~더라고요")는 직접 느낀 걸 말할 때 한 번 정도만.
- 한 문장은 10~25자쯤으로 짧게, 한 문장을 한 줄에. 생각이 바뀌면 빈 줄로 문단을 나눠. 한 문단은 1~3줄.
- 흐름은 "있었던 일이나 사실 → 이유 한두 줄 → 한 줄 마무리(다짐이나 사과나 안내)". 신메뉴는 길게 설명하지 말고 한 줄 선언부터 시작해도 좋아.
- 자주 쓰는 표현: "제가", "손님께", "미리 말씀드립니다", "평소대로", "다시", "죄송합니다". 억지로 다 넣지는 말고 자연스러울 때만.
- 솔직하게, 숨기는 것 없이. 홍보 문구 같은 과장과 권유("놓치지 마세요", "꼭 오세요")는 쓰지 마. 사실만 알리고 판단은 손님에게 맡겨.
- 느낌표(!), 물결(~), "ㅎㅎ" 같은 표현은 쓰지 마.

공통 규칙:
- 가게 정보에 없는 사실(가격, 시간, 메뉴 등)은 지어내지 마.

1) 인스타그램용
- 버전은 "감성형", "정보형", "이벤트형" 3가지.
- 각 문구는 공백 포함 150자 안팎 (130~170자).
- 이모지는 쓰지 않는 게 기본. 꼭 어울릴 때만 문구마다 최대 1개.
- 해시태그는 지역명 + 업종 + 메뉴를 조합해 정확히 10개. 각각 '#'로 시작, 띄어쓰기 없이.

2) 네이버 블로그용
- 제목 1개와 본문 1편. 본문은 공백 포함 1000자 안팎 (900~1100자).
- 가게 소개, 신메뉴 이야기, 할인 안내 순서로 문단을 나눠 써. 문단 사이는 빈 줄. 길이는 채우되 문장은 위 말투 규칙대로 짧게 유지하고, 늘어지는 수식어로 분량을 채우지 마.
- 이모지는 쓰지 마.
- 본문 끝에 어울리는 해시태그 10개 안팎(각각 '#'로 시작, 띄어쓰기 없이)을 따로 줘.

3) 카카오톡 단골 공지용
- 3줄 이내, 아주 짧게. 존댓말. 줄바꿈은 \\n으로 표시.
- 신메뉴와 할인 조건을 꼭 담아. 이모지는 쓰지 마.

반드시 아래 JSON 형식으로만 답해. 다른 설명은 쓰지 마.
{{"인스타그램": {{"감성형": "...", "정보형": "...", "이벤트형": "...", "해시태그": ["#...", "..."]}},
 "블로그": {{"제목": "...", "본문": "...", "해시태그": ["#...", "..."]}},
 "카카오톡": "..."}}"""

    try:
        import anthropic

        응답 = anthropic.Anthropic(api_key=키).messages.create(
            model="claude-sonnet-5-5",
            max_tokens=4000,
            messages=[{"role": "user", "content": 요청}],
        )
        본문 = "".join(b.text for b in 응답.content if b.type == "text").strip()
        본문 = 본문[본문.index("{"): 본문.rindex("}") + 1]
        결과 = json.loads(본문)
        구분선 = "=" * 40
        줄들 = [f"{구분선}\n 인스타그램용\n{구분선}\n"]
        인스타 = 결과["인스타그램"]
        for 이름 in ("감성형", "정보형", "이벤트형"):
            글 = 인스타[이름].strip()
            줄들.append(f"[{이름}] ({len(글)}자)\n{글}\n")
        줄들.append(f"[해시태그]\n{' '.join(인스타['해시태그'])}\n")

        블로그 = 결과["블로그"]
        본문 = 블로그["본문"].strip()
        줄들.append(f"{구분선}\n 네이버 블로그용 ({len(본문)}자)\n{구분선}\n")
        줄들.append(f"[제목]\n{블로그['제목'].strip()}\n")
        줄들.append(f"[본문]\n{본문}\n")
        줄들.append(f"[해시태그]\n{' '.join(블로그['해시태그'])}\n")

        카톡 = 결과["카카오톡"].strip().replace("\\n", "\n")
        줄들.append(f"{구분선}\n 카카오톡 단골 공지용\n{구분선}\n")
        줄들.append(f"{카톡}\n")
        완성폴더.mkdir(exist_ok=True)
        (완성폴더 / "홍보문구.txt").write_text("\n".join(줄들), encoding="utf-8")
        print("\n홍보 문구를 AI로 만들어 '완성' 폴더의 '홍보문구.txt'에 저장했어요.")
        return True
    except Exception as 오류:
        print(f"\nAI로 홍보 문구 만들기에 실패했어요: {오류}")
        return False


def _쪼개기(문장):
    """'A, B, C' 처럼 쉼표+띄어쓰기로 나뉜 말을 조각으로 나눈다. (5,500원 같은 숫자는 그대로)"""
    return [조각.strip() for 조각 in 문장.split(", ") if 조각.strip()]


def _정보_읽기(정보파일):
    """'가게 정보.txt'를 이름/위치/특징/고객층/이번 주 소식으로 나눈다."""
    정보 = {"이름": "", "위치": "", "특징": [], "고객층": "", "소식": []}
    소식_구간 = False
    for 줄 in 정보파일.read_text(encoding="utf-8-sig").splitlines():
        줄 = 줄.strip()
        if not 줄:
            continue
        if 줄.startswith("이번 주 홍보할 것"):
            소식_구간 = True
            continue
        if 소식_구간 and 줄[0] in "-•·*":
            정보["소식"].append(줄[1:].strip().rstrip("."))
            continue
        if ":" in 줄:
            이름, 값 = [x.strip() for x in 줄.split(":", 1)]
            소식_구간 = False
            if 이름 == "가게 이름":
                정보["이름"] = 값
            elif 이름 == "위치":
                정보["위치"] = 값
            elif 이름 == "가게 특징":
                정보["특징"] = _쪼개기(값)
            elif 이름 == "주 고객층":
                정보["고객층"] = 값
    return 정보


def _해시태그_만들기(정보):
    """지역명 + 업종 + 메뉴를 섞어 해시태그 10개를 만든다."""
    글 = " ".join(정보["소식"])
    지역 = 정보["위치"].split()
    후보 = []
    if len(지역) >= 2:
        후보 += [f"{지역[0]}카페", f"{지역[1]}카페", f"{지역[0]}{지역[1]}카페", f"{지역[0]}커피"]
    elif 지역:
        후보 += [f"{지역[0]}카페", f"{지역[0]}커피"]
    if len(지역) > 2:
        후보.append("".join(지역[2:]))
    for 단어 in 지역[2:]:
        if 단어 not in ("지구", "일대", "근처"):
            후보.append(단어)
    특징글 = " ".join(정보["특징"])
    if "스페셜티" in 특징글:
        후보.append("스페셜티커피")
    if "로스팅" in 특징글:
        후보.append("로스터리카페")
    메뉴들 = re.findall(r"['‘\"“]([^'’\"”]+)['’\"”]", 글)
    for 메뉴 in 메뉴들:
        후보.append(메뉴.replace(" ", ""))
    if "신메뉴" in 글:
        후보 += ["신메뉴", "카페신메뉴"]
    if "할인" in 글:
        후보.append("카페할인")
    if 정보["이름"]:
        후보.append(정보["이름"].replace(" ", ""))
    후보 += ["카페스타그램", "커피스타그램", "카페추천", "직장인카페", "혼카페", "동네카페", "오늘의커피"]
    태그 = []
    for 단어 in 후보:
        단어 = "#" + 단어.lstrip("#")
        if 단어 not in 태그:
            태그.append(단어)
    return 태그[:10]


def 틀로_문구_만들기():
    """(API 키가 없을 때) 가게 정보를 정해진 틀에 끼워 넣어 '완성/홍보문구.txt'를 만든다."""
    정보파일 = 파일_찾기(["가게정보.txt", "가게 정보.txt"])
    if not 정보파일:
        print("\n'가게 정보.txt' 파일이 없어서 홍보 문구는 건너뛰었어요.")
        return
    정보 = _정보_읽기(정보파일)
    소식 = 정보["소식"]
    if not 소식:
        print("\n'가게 정보.txt'의 '이번 주 홍보할 것:' 아래에 '- 내용' 줄이 없어서 홍보 문구는 건너뛰었어요.")
        return

    이름 = 정보["이름"] or "저희 가게"
    위치 = 정보["위치"]
    특징 = 정보["특징"]
    첫소식 = 소식[0]
    첫제목 = _쪼개기(첫소식)[0]
    이벤트 = next((s for s in 소식 if any(w in s for w in ("할인", "이벤트", "증정", "무료", "쿠폰", "%"))), 소식[-1])
    다른소식 = next((s for s in 소식 if s != 이벤트), None)
    가게줄 = f"{위치}에서 기다리겠습니다." if 위치 else "기다리겠습니다."

    # 인스타그램 3가지
    감성 = [f"{이름}입니다.", ""]
    감성 += [f"{t}." for t in 특징[:2]]
    감성 += ["", "이번 주 소식입니다.", f"{첫제목}.", "", 가게줄]
    정보형 = [f"이번 주 {이름} 안내입니다.", ""] + [f"- {s}" for s in 소식]
    if 위치:
        정보형 += ["", f"위치: {위치}"]
    이벤트제목 = "할인 안내" if "할인" in 이벤트 else "이벤트 안내"
    이벤트형 = [f"이번 주 {이벤트제목}입니다.", "", f"{이벤트}."]
    if 다른소식:
        이벤트형 += ["", f"{_쪼개기(다른소식)[0]}도 있습니다."]
    이벤트형 += ["", 가게줄]
    인스타 = [("감성형", 감성), ("정보형", 정보형), ("이벤트형", 이벤트형)]

    # 네이버 블로그
    본문 = [f"안녕하세요. {이름}입니다.", ""]
    if 위치:
        본문 += [f"저희 가게는 {위치}에 있습니다."]
    if 특징:
        본문 += ["가게의 특징은 이렇습니다."] + [f"- {t}" for t in 특징]
    if 정보["고객층"]:
        본문 += ["", f"주로 찾아 주시는 분들은 {정보['고객층']}입니다.",
                 "오시는 분들이 편하게 머물다 가실 수 있게 준비하고 있습니다."]
    본문 += ["", "이번 주 소식을 알려드립니다.", ""]
    순서 = ["하나", "둘", "셋", "넷", "다섯", "여섯"]
    for i, 항목 in enumerate(소식):
        조각 = _쪼개기(항목)
        본문 += [f"{순서[i] if i < len(순서) else i + 1}. {조각[0]}"] + [f"- {t}" for t in 조각[1:]] + [""]
    본문 += ["한눈에 정리하면 이렇습니다."] + [f"- {s}" for s in 소식]
    본문 += ["", "자세한 내용은 가게에서 편하게 물어봐 주십시오.", 가게줄, "읽어 주셔서 감사합니다."]
    본문글 = "\n".join(본문)

    # 카카오톡 (3줄)
    나머지 = " / ".join(소식[2:]) if len(소식) > 2 else ""
    카톡 = [f"안녕하세요, {이름}입니다. 이번 주 소식을 전해드립니다.", f"- {소식[0]}"]
    if len(소식) > 1:
        카톡.append(f"- {소식[1]}" + (f" / {나머지}" if 나머지 else ""))

    구분선 = "=" * 40
    줄들 = [f"{구분선}\n 인스타그램용\n{구분선}\n"]
    for 이름표, 줄 in 인스타:
        글 = "\n".join(줄)
        줄들.append(f"[{이름표}] ({len(글)}자)\n{글}\n")
    줄들.append(f"[해시태그]\n{' '.join(_해시태그_만들기(정보))}\n")
    줄들.append(f"{구분선}\n 네이버 블로그용 ({len(본문글)}자)\n{구분선}\n")
    줄들.append(f"[제목]\n{이름} 이번 주 소식 - {첫제목}\n")
    줄들.append(f"[본문]\n{본문글}\n")
    줄들.append(f"[해시태그]\n{' '.join(_해시태그_만들기(정보))}\n")
    줄들.append(f"{구분선}\n 카카오톡 단골 공지용\n{구분선}\n")
    줄들.append("\n".join(카톡) + "\n")
    완성폴더.mkdir(exist_ok=True)
    (완성폴더 / "홍보문구.txt").write_text("\n".join(줄들), encoding="utf-8")
    print("\n홍보 문구를 기본 틀로 만들어 '완성' 폴더의 '홍보문구.txt'에 저장했어요.")


