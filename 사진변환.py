def main():
    if not 자료폴더.is_dir():
        print("'자료' 폴더를 찾을 수 없어요. 이 파일과 같은 곳에 '자료' 폴더가 있어야 해요.")
        return
    완성폴더.mkdir(exist_ok=True)

    로고경로 = 로고_찾기()
    로고 = 로고_준비(로고경로) if 로고경로 else None
    if 로고:
        print(f"로고를 넣을게요: {로고경로.name}")
    else:
        print("로고 파일이 없어서 로고 없이 진행해요.")

    사진들 = sorted(
        p for p in 자료폴더.iterdir()
        if p.is_file()
        and p.suffix.lower() in (".jpg", ".jpeg", ".png")
        and p != 로고경로
    )
    if not 사진들:
        print("'자료' 폴더에 jpg, png 사진이 없어요.")
        return

    접두사 = date.today().strftime("%Y%m%d")
    번호 = 다음_번호(접두사)
    성공 = 0
    for 사진경로 in 사진들:
        try:
            with Image.open(사진경로) as 원본:
                결과 = 정사각형으로_자르기(원본)
            if 로고:
                결과 = 로고_넣기(결과, 로고)
            저장경로 = 완성폴더 / f"{접두사}_{번호:02d}.jpg"
            결과.save(저장경로, "JPEG", quality=95)
            print(f"완료: {사진경로.name} -> {저장경로.name}")
            번호 += 1
            성공 += 1
        except Exception as 오류:
            print(f"건너뜀: {사진경로.name} ({오류})")

    print(f"\n총 {성공}장을 '완성' 폴더에 저장했어요.")
    문구_만들기()


if __name__ == "__main__":
    main()
